import { type ClickHouseClient, createClient } from "@clickhouse/client";

import type { ClickHouseConfig } from "../config.ts";

export type { ClickHouseClient };

/** Unqualified table names let tests use an isolated database. */
export function createClickHouse(
  config: ClickHouseConfig,
  { database = config.database }: { database?: string } = {},
): ClickHouseClient {
  return createClient({
    url: config.url,
    username: config.username,
    password: config.password,
    database,
    application: "ottertrail",
    // Long reports use the server limits in deploy/clickhouse/.
    // Progress headers keep their connections from appearing idle.
    request_timeout: 120_000,
    clickhouse_settings: {
      send_progress_in_http_headers: 1,
      http_headers_progress_interval_ms: "10000",
      // Quote 64-bit integers to avoid JavaScript rounding. ClickHouse 26 sends them bare by default.
      output_format_json_quote_64bit_integers: 1,
    },
  });
}

/** Use only for names generated by Ottertrail. */
export function identifier(name: string): string {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) {
    throw new Error(`Not a safe ClickHouse identifier: ${name}`);
  }
  return `\`${name}\``;
}
