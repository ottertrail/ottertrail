import type { ClickHouseClient } from "../clickhouse/clickhouse.ts";
import { insertRows } from "../clickhouse/insert.ts";
import { clickHouseTime } from "../clickhouse/query.ts";
import type { JsonObject } from "../db/schema.ts";
import type { Location } from "../enrichment/geo.ts";
import type { Client } from "../enrichment/user-agent.ts";
import { DEFAULT_ENVIRONMENT } from "./environment.ts";

export interface Utm {
  source?: string;
  medium?: string;
  campaign?: string;
  term?: string;
  content?: string;
}

/** An event that has already passed validation (collection/routes.ts, server-events.ts). */
export interface NewEvent {
  /** Generated by the sender; makes retries safe. */
  eventId: string;
  name: string;
  /** Sender's clock. */
  occurredAt: Date;
  /** Page path; left out for a server-side event that names no page. */
  path?: string;
  referrer?: string;
  utm?: Utm;
  properties?: JsonObject;
  /** Browser, OS, and device, from the request's User-Agent. */
  client?: Client;
  /** Country, region, and city, from the request's IP address. */
  location?: Location;
  /** Daily cookieless visitor ID (see visitors/visitor-ids.ts). */
  visitorId?: string;
  /** Where the app runs, in lower case; "production" when left out (collection/environment.ts). */
  environment?: string;
  /** The app's version, such as "1.4.2". */
  release?: string;
  /** The site's own ID for the signed-in user (collection/identity.ts). */
  userId?: string;
  /** For an "error" event: what went wrong, and its group (errors/fingerprint.ts). */
  error?: StoredError;
  /** For a server's exception received over OTLP: where it happened (telemetry/exceptions.ts). */
  server?: ServerOrigin;
}

/** The service, trace, and span a server's exception happened in. */
export interface ServerOrigin {
  /** The resource's service.name. */
  service: string;
  /** In hex, as the spans table has them; "" when the record had none. */
  traceId: string;
  spanId: string;
}

export interface StoredError {
  type: string;
  message: string;
  stack?: string;
  handled: boolean;
  fingerprint: string;
  /** The session replay that shows it, when the page recorded one (docs/session-replay.md). */
  replayId?: string;
}

/**
 * One event, column by column: what storeEvents() builds from a NewEvent
 * for ClickHouse, and how tests read events back (tests/helpers/events.ts).
 */
export interface EventRow {
  project_id: string;
  event_id: string;
  name: string;
  occurred_at: Date;
  received_at: Date;
  path: string | null;
  referrer: string | null;
  utm_source: string | null;
  utm_medium: string | null;
  utm_campaign: string | null;
  utm_term: string | null;
  utm_content: string | null;
  properties: JsonObject;
  browser: string | null;
  browser_version: string | null;
  os: string | null;
  device_type: string | null;
  country: string | null;
  region: string | null;
  city: string | null;
  /** A signed 64-bit integer, as a string: a JavaScript number would round it. */
  visitor_id: string | null;
  environment: string;
  release: string | null;
  user_id: string | null;
  error_type: string | null;
  error_message: string | null;
  error_stack: string | null;
  error_handled: boolean | null;
  error_fingerprint: string | null;
  replay_id: string | null;
  /** A server's exception's (ServerOrigin); "" for every other event. */
  service: string;
  trace_id: string;
  span_id: string;
}

/** One event as ClickHouse's events table takes it (clickhouse/migrations.ts). */
export function toClickHouse(event: EventRow) {
  return {
    project_id: event.project_id,
    event_id: event.event_id,
    name: event.name,
    occurred_at: clickHouseTime(event.occurred_at),
    received_at: clickHouseTime(event.received_at),
    // ClickHouse's path is not nullable: a server-side event without a page has "".
    path: event.path ?? "",
    referrer: event.referrer,
    utm_source: event.utm_source,
    utm_medium: event.utm_medium,
    utm_campaign: event.utm_campaign,
    utm_term: event.utm_term,
    utm_content: event.utm_content,
    properties: JSON.stringify(event.properties),
    browser: event.browser,
    browser_version: event.browser_version,
    os: event.os,
    device_type: event.device_type,
    country: event.country,
    region: event.region,
    city: event.city,
    // A string; ClickHouse reads it as Int64.
    visitor_id: event.visitor_id,
    environment: event.environment,
    release: event.release,
    user_id: event.user_id,
    // Empty for every event but an error: ClickHouse's columns are not nullable.
    error_type: event.error_type ?? "",
    error_message: event.error_message ?? "",
    error_stack: event.error_stack ?? "",
    error_handled: event.error_handled ?? false,
    error_fingerprint: event.error_fingerprint ?? "",
    replay_id: event.replay_id,
    service: event.service,
    trace_id: event.trace_id,
    span_id: event.span_id,
  };
}

/**
 * One event's row, as storeEvents() writes it. Exported for the
 * development seed (scripts/seed-data.ts), which stores events with the
 * times they arrived in the past, each its own.
 */
export function toRow(projectId: string, event: NewEvent, receivedAt: Date): EventRow {
  return {
    project_id: projectId,
    event_id: event.eventId,
    name: event.name,
    occurred_at: event.occurredAt,
    received_at: receivedAt,
    path: event.path ?? null,
    referrer: event.referrer ?? null,
    utm_source: event.utm?.source ?? null,
    utm_medium: event.utm?.medium ?? null,
    utm_campaign: event.utm?.campaign ?? null,
    utm_term: event.utm?.term ?? null,
    utm_content: event.utm?.content ?? null,
    properties: event.properties ?? {},
    browser: event.client?.browser ?? null,
    browser_version: event.client?.browserVersion ?? null,
    os: event.client?.os ?? null,
    device_type: event.client?.deviceType ?? null,
    country: event.location?.country ?? null,
    region: event.location?.region ?? null,
    city: event.location?.city ?? null,
    visitor_id: event.visitorId ?? null,
    environment: event.environment ?? DEFAULT_ENVIRONMENT,
    release: event.release ?? null,
    user_id: event.userId ?? null,
    error_type: event.error?.type ?? null,
    error_message: event.error?.message ?? null,
    error_stack: event.error?.stack ?? null,
    error_handled: event.error?.handled ?? null,
    error_fingerprint: event.error?.fingerprint ?? null,
    replay_id: event.error?.replayId ?? null,
    service: event.server?.service ?? "",
    trace_id: event.server?.traceId ?? "",
    span_id: event.server?.spanId ?? "",
  };
}

/**
 * Stores events for one project in ClickHouse, in one insert, and returns
 * once ClickHouse has written them (clickhouse/insert.ts): either all are
 * stored or the call fails.
 *
 * Senders retry when they do not hear back, so the same event can arrive
 * twice. Nothing is looked up: a retry is the same row, (project_id,
 * occurred_at, event_id), and the table keeps one of each when it merges
 * parts (ReplacingMergeTree), which reports read with FINAL. A browser
 * event's time is corrected the same way on every attempt for this
 * (correctClock in normalize.ts); a server's is stored as sent.
 */
export async function storeEvents(
  clickhouse: ClickHouseClient,
  projectId: string,
  events: readonly NewEvent[],
  { receivedAt = new Date() }: { receivedAt?: Date } = {},
): Promise<void> {
  await insertRows(
    clickhouse,
    "events",
    events.map((event) => toClickHouse(toRow(projectId, event, receivedAt))),
  );
}
