import type { ColumnType } from "kysely";

/**
 * TypeScript view of the database tables, used by Kysely to check queries.
 * Keep it in step with the migrations in ./migrations.
 *
 * ColumnType<Select, Insert, Update> describes what a column returns when
 * read, and what it accepts on insert and update.
 */

/** Set by the database on insert; never written by the application. */
type DatabaseDefault<T> = ColumnType<T, never, never>;

/** Optional on insert: leaving it out stores NULL. */
type Nullable<T> = ColumnType<T | null, T | null | undefined, T | null>;

export type JsonObject = { [key: string]: unknown };

export interface ProjectsTable {
  id: ColumnType<string, string | undefined, never>;
  name: string;
  created_at: DatabaseDefault<Date>;
  /** "pk_" + 32 hex characters. Public: identifies the project to the collection endpoint. */
  public_key: ColumnType<string, string | undefined, string>;
  /** Sites whose pages may send events, such as "example.com". Empty accepts nothing. */
  allowed_hostnames: ColumnType<string[], string[] | undefined, string[]>;
}

/**
 * One row per thing that happened. Reports are always computed from these
 * rows; nothing stores running totals.
 */
export interface EventsTable {
  project_id: string;
  /** Generated by the sender. Unique per project, so a retried send is stored once. */
  event_id: string;
  /** "pageview" or a custom event name such as "signup". */
  name: string;
  /** When it happened, by the sender's clock. Reports use this time. */
  occurred_at: ColumnType<Date, Date, never>;
  /** When the server received it, by the server's clock. */
  received_at: DatabaseDefault<Date>;
  /** Page path without the query string, for example "/lessons/closures". */
  path: string;
  referrer: Nullable<string>;
  utm_source: Nullable<string>;
  utm_medium: Nullable<string>;
  utm_campaign: Nullable<string>;
  utm_term: Nullable<string>;
  utm_content: Nullable<string>;
  /** Custom details, such as { plan: "free" }. Always a JSON object, at most 8 KB. */
  properties: ColumnType<JsonObject, JsonObject | undefined, JsonObject>;
  /** From the User-Agent header, such as "Chrome". */
  browser: Nullable<string>;
  /** Major version only, such as "142". */
  browser_version: Nullable<string>;
  /** OS name only, such as "macOS". */
  os: Nullable<string>;
  device_type: Nullable<"desktop" | "mobile" | "tablet" | "tv">;
  /** From the client's IP address (never stored): ISO country code, such as "DE". */
  country: Nullable<string>;
  /** English region name, such as "Bavaria". */
  region: Nullable<string>;
  /** English city name, such as "Munich". */
  city: Nullable<string>;
  /**
   * Same browser, same network, same project, same day (in the instance's
   * timezone): same ID. A signed 64-bit integer; PostgreSQL's bigint arrives
   * as a string.
   */
  visitor_id: Nullable<string>;
  /**
   * For events in the first 30 minutes of a day: the visitor's ID under the
   * previous day's salt, so a visit that crosses midnight stays one visit.
   */
  previous_visitor_id: Nullable<string>;
}

/** One random secret per day. Deleted once no event can still need it. */
export interface VisitorSaltsTable {
  /** "YYYY-MM-DD" in the instance's timezone (date columns arrive as strings; see database.ts). */
  day: ColumnType<string, string, never>;
  salt: ColumnType<Buffer, Buffer, never>;
  created_at: DatabaseDefault<Date>;
}

export interface Database {
  projects: ProjectsTable;
  events: EventsTable;
  visitor_salts: VisitorSaltsTable;
}
